/// A lone name: a binary property or a `General_Category` value.
pub(crate) fn is_lone_name(name: &str) -> bool {
    BINARY.contains(&name) || GENERAL_CATEGORY.contains(&name)
}

/// A lone name that is a binary property of strings (`\p{RGI_Emoji}`).
pub(crate) fn is_string_property(name: &str) -> bool {
    STRINGS.contains(&name)
}

/// `Name=Value`: `General_Category` with one of its values, or `Script` /
/// `Script_Extensions` with a script.
pub(crate) fn is_pair(name: &str, value: &str) -> bool {
    match name {
        "General_Category" | "gc" => GENERAL_CATEGORY.contains(&value),
        "Script" | "sc" | "Script_Extensions" | "scx" => SCRIPT.contains(&value),
        _ => false,
    }
}

#[cfg(test)]
mod tests {
    use super::{
        is_lone_name, is_pair, is_string_property, BINARY, GENERAL_CATEGORY, SCRIPT, STRINGS,
    };

    #[test]
    fn every_table_entry_is_accepted_in_its_place_only() {
        for name in BINARY.iter().chain(GENERAL_CATEGORY) {
            assert!(is_lone_name(name), "{name}");
            assert!(!is_string_property(name), "{name}");
            assert!(!is_pair("Script", name), "{name}");
        }
        for name in STRINGS {
            assert!(is_string_property(name), "{name}");
            assert!(!is_lone_name(name), "{name}");
        }
        for value in GENERAL_CATEGORY {
            assert!(is_pair("General_Category", value), "{value}");
            assert!(is_pair("gc", value), "{value}");
            assert!(!is_pair("sc", value), "{value}");
        }
        for value in SCRIPT {
            for name in ["Script", "sc", "Script_Extensions", "scx"] {
                assert!(is_pair(name, value), "{name}={value}");
            }
            assert!(!is_pair("gc", value), "{value}");
            assert!(
                !is_lone_name(value),
                "a script is never a lone name: {value}"
            );
        }
        assert_eq!(BINARY.len(), 98);
        assert_eq!(STRINGS.len(), 7);
        assert_eq!(GENERAL_CATEGORY.len(), 80);
        assert_eq!(SCRIPT.len(), 334);
    }

    #[test]
    fn matching_is_exact_and_case_sensitive() {
        for name in [
            "ascii",
            "LU",
            "lu",
            "letter",
            "",
            "L ",
            " L",
            "Script",
            "Latin",
            "RGI_emoji",
        ] {
            assert!(!is_lone_name(name), "{name}");
            assert!(!is_string_property(name), "{name}");
        }
        assert!(!is_pair("script", "Latin"));
        assert!(!is_pair("Script", "latin"));
        assert!(!is_pair("Script", ""));
        assert!(!is_pair("", "Latin"));
        assert!(!is_pair("Alphabetic", "Yes"));
        assert!(!is_pair("RGI_Emoji", "Yes"));
    }

    #[test]
    fn no_table_has_duplicates() {
        for table in [BINARY, STRINGS, GENERAL_CATEGORY, SCRIPT] {
            let mut sorted = table.to_vec();
            sorted.sort_unstable();
            sorted.dedup();
            assert_eq!(sorted.len(), table.len());
        }
    }
}
